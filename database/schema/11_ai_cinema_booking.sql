create or replace function search_cinema_movies (
   p_title      in varchar2 default null,
   p_genre      in varchar2 default null,
   p_min_rating in number default null
) return clob is
   l_result clob;
begin
   select coalesce(
      json_arrayagg(
         json_object(
            'id' value m.id,
                     'title' value m.title,
                     'genre' value m.genre,
                     'duration_minutes' value m.duration_minutes,
                     'rating' value m.rating
         returning clob)
      returning clob),
      to_clob('[]')
   )
     into l_result
     from cinema_movies m
    where m.is_active = 'Y'
      and ( p_title is null
       or upper(m.title) like '%'
                              || upper(p_title)
                              || '%' )
      and ( p_genre is null
       or upper(m.genre) = upper(p_genre) )
      and ( p_min_rating is null
       or m.rating >= p_min_rating );

   return l_result;
end;
/

create or replace function find_available_showtimes (
   p_date     in date,
   p_guests   in number,
   p_genre    in varchar2 default null,
   p_min_time in varchar2 default null
) return clob is
   l_result clob;
begin
   select coalesce(
      json_arrayagg(
         json_object(
            'showtime_id' value s.id,
                     'movie_id' value m.id,
                     'title' value m.title,
                     'genre' value m.genre,
                     'show_date' value to_char(
               s.show_date,
               'YYYY-MM-DD'
            ),
                     'show_time' value s.show_time,
                     'available_seats' value s.available_seats,
                     'ticket_price' value s.ticket_price
         returning clob)
       order by s.show_time returning clob),
      to_clob('[]')
   )
     into l_result
     from cinema_showtimes s
     join cinema_movies m
   on m.id = s.movie_id
    where m.is_active = 'Y'
      and trunc(s.show_date) = trunc(p_date)
      and s.available_seats >= p_guests
      and ( p_genre is null
       or upper(m.genre) = upper(p_genre) )
      and ( p_min_time is null
       or s.show_time >= p_min_time );

   return l_result;
end;
/

create or replace procedure book_movie_tickets (
   p_showtime_id    in number,
   p_customer_name  in varchar2,
   p_customer_email in varchar2,
   p_seat_count     in number,
   p_result         out clob
) is
   l_available_seats number;
   l_ticket_price    number;
   l_total_price     number;
   l_booking_id      number;
   l_error_message   varchar2(4000);
begin
   if p_seat_count is null
   or p_seat_count <= 0 then
      select
         json_object(
            'success' value false,
                     'error' value 'Seat count must be greater than zero'
         returning clob)
        into p_result
        from dual;

      return;
   end if;


   begin
      select available_seats,
             ticket_price
        into
         l_available_seats,
         l_ticket_price
        from cinema_showtimes
       where id = p_showtime_id
      for update;

   exception
      when no_data_found then
         select
            json_object(
               'success' value false,
                        'error' value 'Showtime not found'
            returning clob)
           into p_result
           from dual;

         return;
   end;


   if l_available_seats < p_seat_count then
      select
         json_object(
            'success' value false,
                     'error' value 'Not enough available seats',
                     'available_seats' value l_available_seats
         returning clob)
        into p_result
        from dual;

      return;
   end if;


   l_total_price := l_ticket_price * p_seat_count;
   insert into cinema_bookings (
      showtime_id,
      customer_name,
      customer_email,
      seat_count,
      total_price,
      booking_status
   ) values
      ( p_showtime_id,
        p_customer_name,
        p_customer_email,
        p_seat_count,
        l_total_price,
        'CONFIRMED' )
   returning id into l_booking_id;


   update cinema_showtimes
      set
      available_seats = available_seats - p_seat_count
    where id = p_showtime_id;


   commit;
   select
      json_object(
         'success' value true,
                  'booking_id' value l_booking_id,
                  'showtime_id' value p_showtime_id,
                  'customer_name' value p_customer_name,
                  'seat_count' value p_seat_count,
                  'ticket_price' value l_ticket_price,
                  'total_price' value l_total_price,
                  'booking_status' value 'CONFIRMED'
      returning clob)
     into p_result
     from dual;


exception
   when others then
      l_error_message := sqlerrm;
      rollback;
      select
         json_object(
            'success' value false,
                     'error' value l_error_message
         returning clob)
        into p_result
        from dual;

end;
/


create or replace procedure cancel_movie_booking (
   p_booking_id in number,
   p_result     out clob
) is
   l_showtime_id   number;
   l_seat_count    number;
   l_status        varchar2(30);
   l_error_message varchar2(4000);
begin
   begin
      select showtime_id,
             seat_count,
             booking_status
        into
         l_showtime_id,
         l_seat_count,
         l_status
        from cinema_bookings
       where id = p_booking_id
      for update;

   exception
      when no_data_found then
         select
            json_object(
               'success' value false,
                        'error' value 'Booking not found'
            returning clob)
           into p_result
           from dual;

         return;
   end;


   if l_status = 'CANCELLED' then
      select
         json_object(
            'success' value false,
                     'error' value 'Booking is already cancelled'
         returning clob)
        into p_result
        from dual;

      return;
   end if;


   update cinema_showtimes
      set
      available_seats = available_seats + l_seat_count
    where id = l_showtime_id;


   update cinema_bookings
      set
      booking_status = 'CANCELLED'
    where id = p_booking_id;


   commit;
   select
      json_object(
         'success' value true,
                  'booking_id' value p_booking_id,
                  'showtime_id' value l_showtime_id,
                  'returned_seats' value l_seat_count,
                  'booking_status' value 'CANCELLED'
      returning clob)
     into p_result
     from dual;


exception
   when others then
      l_error_message := sqlerrm;
      rollback;
      select
         json_object(
            'success' value false,
                     'error' value l_error_message
         returning clob)
        into p_result
        from dual;

end;
