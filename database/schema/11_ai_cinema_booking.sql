create table cinema_movies (
   id               number generated by default as identity,
   title            varchar2(200) not null,
   genre            varchar2(50),
   duration_minutes number,
   rating           number(2,1),
   is_active        char(1) default 'Y',
   constraint cinema_movies_pk primary key ( id ),
   constraint cinema_movies_ck check ( is_active in ( 'Y',
                                                      'N' ) )
);

create table cinema_showtimes (
   id              number generated by default as identity,
   movie_id        number not null,
   show_date       date not null,
   show_time       varchar2(5) not null,
   total_seats     number not null,
   available_seats number not null,
   ticket_price    number(10,2) not null,
   constraint cinema_showtimes_pk primary key ( id ),
   constraint cinema_showtimes_fk foreign key ( movie_id )
      references cinema_movies ( id )
);

create table cinema_bookings (
   id             number generated by default as identity,
   showtime_id    number not null,
   customer_name  varchar2(200) not null,
   customer_email varchar2(200),
   seat_count     number not null,
   total_price    number(10,2),
   booking_status varchar2(30) default 'CONFIRMED',
   created_at     date default sysdate,
   constraint cinema_bookings_pk primary key ( id ),
   constraint cinema_bookings_fk foreign key ( showtime_id )
      references cinema_showtimes ( id )
);

